"""Regenerates memory/MEMORY.md: a short (<300 lines) human/agent-readable summary. Never contains raw JDs."""

from __future__ import annotations

from collections import Counter, defaultdict
from typing import Any

MAX_LINES = 300


def learned_notes(snapshot: list[dict[str, Any]], limit: int = 25) -> list[str]:
    """E.g. 'CloudKart calls L2 "SDE 2"'. Per company, the most common title per level, if seen ≥2 times
    or if it carries an explicit level signal."""
    by: dict[tuple[str, str], Counter] = defaultdict(Counter)
    for r in snapshot:
        if r.get("company") and r.get("level") and r.get("level_signals"):
            if any(str(s).startswith("title:") for s in r["level_signals"]):
                by[(r["company"], r["level"])][r["title"]] += 1
    notes = []
    for (company, level), ctr in sorted(by.items()):
        title, n = ctr.most_common(1)[0]
        notes.append(f'- {company} calls {level} "{title}"' + (f" ({n}×)" if n > 1 else ""))
    return notes[:limit]


def render_memory(day: str, data: dict[str, Any], stats: dict[str, Any], snapshot: list[dict[str, Any]],
                  last_run: dict[str, Any] | None) -> str:
    L = ["# MEMORY.md — SkillPulse state summary", "",
         f"_Regenerated by the daily run on {day}. Do not edit by hand. Source of truth is data/skillpulse.db._", "",
         "## Totals", "",
         f"- Unique postings stored: {stats['postings']} · extractions: {stats['extractions']} · runs: {stats['runs']}",
         f"- Postings by level: " + ", ".join(f"{k} {v}" for k, v in stats["by_level"].items()),
         f"- Postings by status: " + ", ".join(f"{k} {v}" for k, v in stats["by_status"].items()),
         f"- Postings by source: " + ", ".join(f"{k} {v}" for k, v in stats["by_source"].items()),
         f"- Dedupe hit rate (all time): {stats['dedupe_hit_rate']}% · total LLM spend: ${stats['llm_cost_usd_total']}",
         ]
    if last_run:
        fetched = last_run.get("postings_fetched") or 0
        cached = last_run.get("postings_cached") or 0
        L.append(f"- Last run: {last_run.get('run_date')} ({last_run.get('status')}), cache hit rate "
                 f"{(100 * cached / fetched) if fetched else 0:.0f}%, cost ${last_run.get('cost_usd') or 0:.4f}")
    L += ["", "## Latest top skills per family × level", ""]
    for fam in data.get("families", []):
        for lv in fam["levels"]:
            top = ", ".join(f"{s['skill']} {s['share']:.0f}%" for s in lv["top_skills"][:5])
            L.append(f"- **{fam['label']} {lv['level']}** (n={lv['n']}): {top}")
    L += ["", "## Learned notes", ""]
    notes = learned_notes(snapshot)
    L += notes or ["- (none yet)"]
    L += ["", "## Pointers", "",
          "- Level rules: memory/LEVEL_RUBRIC.md · aliases: memory/skill_aliases.yaml · docs: AGENTS.md", ""]
    if len(L) > MAX_LINES:
        L = L[: MAX_LINES - 1] + ["_(truncated to stay under 300 lines)_"]
    return "\n".join(L)

